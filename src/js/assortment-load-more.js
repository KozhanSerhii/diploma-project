const assortmentList = document.querySelector('.assortment-list');
const loadMoreBtn = document.querySelector('.assortment-load-more-btn');
const filterButtons = document.querySelectorAll('.assortment-filter-btn');

const itemsPerStep = 4;
const ADMIN_PRODUCTS_KEY = 'ecotote-admin-products';
const CART_KEY = 'ecotote-cart';

let activeFilter = 'all';
let visibleItemsCount = itemsPerStep;

function getProductsForCatalog() {
  const adminProducts = JSON.parse(localStorage.getItem(ADMIN_PRODUCTS_KEY)) || [];

  if (adminProducts.length === 0) {
    return products.map(product => ({
      ...product,
      stock: 99,
      status: 'Активний',
    }));
  }

  const mergedProducts = products
    .map(product => {
      const adminProduct = adminProducts.find(item => item.name === product.name);

      if (!adminProduct) {
        return {
          ...product,
          stock: 99,
          status: 'Активний',
        };
      }

      if (adminProduct.status !== 'Активний') {
        return null;
      }

      return {
        ...product,
        name: adminProduct.name || product.name,
        category: adminProduct.category || product.category,
        description: adminProduct.description || product.description,
        shortDescription: adminProduct.description || product.shortDescription,
        price: `₴${adminProduct.price}`,
        stock: Number(adminProduct.stock) || 0,
        status: adminProduct.status || 'Активний',
        image: product.image,
        imageTab: product.imageTab,
        imageDesk: product.imageDesk,
        image2x: product.image2x,
        imageTab2x: product.imageTab2x,
        imageDesk2x: product.imageDesk2x,
        categories: product.categories,
      };
    })
    .filter(Boolean);

  const newAdminProducts = adminProducts
    .filter(adminProduct => {
      const existsInDefaultProducts = products.some(
        product => product.name === adminProduct.name
      );

      return !existsInDefaultProducts && adminProduct.status === 'Активний';
    })
    .map(adminProduct => ({
      name: adminProduct.name,
      category: adminProduct.category,
      description: adminProduct.description,
      shortDescription: adminProduct.description,
      price: `₴${adminProduct.price}`,
      rating: '★★★★★',
      size: '300мм x 250мм x 100мм',
      stock: Number(adminProduct.stock) || 0,
      status: adminProduct.status || 'Активний',
      image: adminProduct.image,
      imageTab: adminProduct.image,
      imageDesk: adminProduct.image,
      image2x: adminProduct.image,
      imageTab2x: adminProduct.image,
      imageDesk2x: adminProduct.image,
      categories: ['all'],
    }));

  return [...mergedProducts, ...newAdminProducts];
}

function getFilteredProducts() {
  const catalogProducts = getProductsForCatalog();

  if (activeFilter === 'all') {
    return catalogProducts;
  }

  return catalogProducts.filter(product =>
    product.categories.includes(activeFilter)
  );
}

function createProductMarkup(product, index) {
  return `
    <li class="assortment-item">
      <picture>
        <source
          srcset="${product.imageDesk} 1x, ${product.imageDesk2x} 2x"
          media="(min-width: 1440px)"
        />
        <source
          srcset="${product.imageTab} 1x, ${product.imageTab2x} 2x"
          media="(min-width: 768px)"
        />
        <source
          srcset="${product.image} 1x, ${product.image2x} 2x"
          media="(max-width: 767px)"
        />
        <img src="${product.image}" alt="${product.name}" />
      </picture>

      <h3 class="assortment-name">${product.name}</h3>
      <p class="assortment-descr">${product.shortDescription}</p>
      <span class="assortment-price">${product.price}</span>
      <button class="assortment-btn" type="button" data-product-index="${index}">
        Детальніше
      </button>
    </li>
  `;
}

function renderProducts() {
  const filteredProducts = getFilteredProducts();
  const visibleProducts = filteredProducts.slice(0, visibleItemsCount);

  assortmentList.innerHTML = visibleProducts
    .map((product, index) => {
      return createProductMarkup(product, index);
    })
    .join('');

  if (visibleItemsCount >= filteredProducts.length) {
    loadMoreBtn.classList.add('is-hidden');
  } else {
    loadMoreBtn.classList.remove('is-hidden');
  }
}

function setActiveFilterButton(activeButton) {
  filterButtons.forEach(button => {
    button.classList.remove('is-active');
  });

  activeButton.classList.add('is-active');
}

function createProductModal() {
  const modalMarkup = `
    <div class="product-modal-backdrop is-hidden">
      <div class="product-modal">
        <button class="product-modal-close" type="button" aria-label="Закрити модальне вікно">
          ×
        </button>

        <div class="product-modal-image-wrap">
          <img class="product-modal-image" src="" alt="" />
        </div>

        <div class="product-modal-content">
          <h2 class="product-modal-title"></h2>
          <p class="product-modal-category"></p>
          <p class="product-modal-price"></p>
          <p class="product-modal-rating"></p>
          <p class="product-modal-description"></p>
          <p class="product-modal-size"></p>
          <p class="product-modal-stock"></p>

          <button class="product-modal-cart-btn" type="button">
            Додати до кошика
          </button>
        </div>
      </div>
    </div>
  `;

  document.body.insertAdjacentHTML('beforeend', modalMarkup);
}

function openProductModal(product) {
  const backdrop = document.querySelector('.product-modal-backdrop');
  const image = document.querySelector('.product-modal-image');
  const title = document.querySelector('.product-modal-title');
  const category = document.querySelector('.product-modal-category');
  const price = document.querySelector('.product-modal-price');
  const rating = document.querySelector('.product-modal-rating');
  const description = document.querySelector('.product-modal-description');
  const size = document.querySelector('.product-modal-size');
  const stockText = document.querySelector('.product-modal-stock');
  const addToCartBtn = document.querySelector('.product-modal-cart-btn');

  const stock = Number(product.stock) || 0;
  const isOutOfStock = stock <= 0 || product.status === 'Неактивний';

  image.src = product.imageDesk;
  image.alt = product.name;
  title.textContent = product.name;
  category.textContent = product.category;
  price.textContent = product.price;
  rating.textContent = product.rating;
  description.textContent = product.description;
  size.textContent = `Розміри: ${product.size}`;

  if (stockText) {
    stockText.textContent = isOutOfStock
      ? 'Немає в наявності'
      : `В наявності: ${stock} шт.`;

    stockText.classList.toggle('is-out', isOutOfStock);
  }

  addToCartBtn.disabled = isOutOfStock;
  addToCartBtn.textContent = isOutOfStock
    ? 'Немає в наявності'
    : 'Додати до кошика';

  addToCartBtn.onclick = () => {
    const currentStock = Number(product.stock) || 0;

    if (currentStock <= 0 || product.status === 'Неактивний') {
      alert(`Товар "${product.name}" наразі недоступний для замовлення.`);
      return;
    }

    const cart = JSON.parse(localStorage.getItem(CART_KEY)) || [];
    const existingProduct = cart.find(item => item.name === product.name);

    if (existingProduct) {
      if (Number(existingProduct.quantity) >= currentStock) {
        alert(`На складі доступно лише ${currentStock} шт. товару "${product.name}".`);
        return;
      }

      existingProduct.quantity += 1;
      existingProduct.stock = currentStock;
      existingProduct.status = product.status || 'Активний';
    } else {
      cart.push({
        name: product.name,
        category: product.category,
        price: product.price,
        image: product.image,
        stock: currentStock,
        status: product.status || 'Активний',
        quantity: 1,
      });
    }

    localStorage.setItem(CART_KEY, JSON.stringify(cart));

    addToCartBtn.textContent = 'Додано до кошика';

    setTimeout(() => {
      addToCartBtn.textContent = 'Додати до кошика';
    }, 1200);
  };

  backdrop.classList.remove('is-hidden');
  document.body.classList.add('modal-open');
}

function closeProductModal() {
  const backdrop = document.querySelector('.product-modal-backdrop');

  backdrop.classList.add('is-hidden');
  document.body.classList.remove('modal-open');
}

function initModalEvents() {
  const backdrop = document.querySelector('.product-modal-backdrop');
  const closeBtn = document.querySelector('.product-modal-close');

  closeBtn.addEventListener('click', closeProductModal);

  backdrop.addEventListener('click', event => {
    if (event.target === backdrop) {
      closeProductModal();
    }
  });

  document.addEventListener('keydown', event => {
    if (event.key === 'Escape') {
      closeProductModal();
    }
  });
}

if (assortmentList) {
  assortmentList.addEventListener('click', event => {
    const detailsBtn = event.target.closest('.assortment-btn');

    if (!detailsBtn) return;

    const productIndex = Number(detailsBtn.dataset.productIndex);
    const filteredProducts = getFilteredProducts();
    const visibleProducts = filteredProducts.slice(0, visibleItemsCount);
    const product = visibleProducts[productIndex];

    openProductModal(product);
  });
}

filterButtons.forEach(button => {
  button.addEventListener('click', () => {
    activeFilter = button.dataset.filter;
    visibleItemsCount = itemsPerStep;

    setActiveFilterButton(button);
    renderProducts();
  });
});

if (loadMoreBtn) {
  loadMoreBtn.addEventListener('click', () => {
    visibleItemsCount += itemsPerStep;
    renderProducts();
  });
}

createProductModal();
initModalEvents();
renderProducts();